-- Kept to the SQL subset shared by PostgreSQL and H2 (MODE=PostgreSQL), which backs the local profile and tests.

create table users (
    id            bigint generated by default as identity primary key,
    username      varchar(20)  not null,
    display_name  varchar(40)  not null,
    password_hash varchar(100) not null,
    created_at    timestamp with time zone not null,
    constraint uq_users_username unique (username)
);

create table teams (
    id                bigint generated by default as identity primary key,
    name              varchar(40) not null,
    rank_points       integer     not null default 0,
    treasury_cut_pct  integer     not null default 20,
    split_mode        varchar(16) not null default 'EQUAL',
    created_at        timestamp with time zone not null,
    version           bigint      not null default 0,
    constraint uq_teams_name unique (name),
    constraint ck_teams_cut check (treasury_cut_pct between 0 and 100)
);

-- Memberships are never deleted: wallets and ledger entries keep pointing at them after someone leaves.
create table memberships (
    id         bigint generated by default as identity primary key,
    team_id    bigint      not null references teams (id),
    user_id    bigint      not null references users (id),
    role       varchar(16) not null,
    joined_at  timestamp with time zone not null,
    left_at    timestamp with time zone,
    version    bigint      not null default 0
);
create index ix_memberships_team on memberships (team_id);
create index ix_memberships_user on memberships (user_id);

create table invitations (
    id             bigint generated by default as identity primary key,
    team_id        bigint      not null references teams (id),
    invitee_id     bigint      not null references users (id),
    invited_by_id  bigint      not null references users (id),
    role           varchar(16) not null,
    status         varchar(16) not null,
    created_at     timestamp with time zone not null,
    expires_at     timestamp with time zone not null,
    responded_at   timestamp with time zone
);
create index ix_invitations_invitee on invitations (invitee_id, status);
create index ix_invitations_team on invitations (team_id, status);

create table recruits (
    id                bigint generated by default as identity primary key,
    team_id           bigint      not null references teams (id),
    species_id        integer     not null,
    nickname          varchar(20),
    level             integer     not null,
    exp               integer     not null,
    status            varchar(16) not null,
    recruited_by_id   bigint      references memberships (id),
    recruited_at      timestamp with time zone not null,
    mission_id        bigint,
    version           bigint      not null default 0
);
create index ix_recruits_team on recruits (team_id, status);

create table missions (
    id                 bigint generated by default as identity primary key,
    team_id            bigint       not null references teams (id),
    title              varchar(80)  not null,
    kind               varchar(16)  not null,
    dungeon_code       varchar(40)  not null,
    floor              integer      not null,
    difficulty         varchar(8)   not null,
    client_species_id  integer,
    reward_poke        integer      not null,
    rank_points        integer      not null,
    status             varchar(16)  not null,
    leader_id          bigint       references memberships (id),
    posted_by_id       bigint       not null references memberships (id),
    posted_at          timestamp with time zone not null,
    departed_at        timestamp with time zone,
    closed_at          timestamp with time zone,
    outcome_note       varchar(280),
    version            bigint       not null default 0
);
create index ix_missions_team on missions (team_id, status);

create table mission_reward_items (
    mission_id  bigint      not null references missions (id),
    item_code   varchar(40) not null,
    quantity    integer     not null
);

create table mission_bag (
    mission_id  bigint      not null references missions (id),
    item_code   varchar(40) not null,
    quantity    integer     not null
);

create table mission_party (
    mission_id  bigint  not null references missions (id),
    position    integer not null,
    recruit_id  bigint  not null references recruits (id),
    primary key (mission_id, position)
);

-- Cached balance per (account, asset). The ledger is the source of truth; /ledger/reconcile recomputes these.
-- account_key: treasury | storage | wallet:<membershipId> | bag:<missionId> | world
-- asset:       POKE | <item code>
create table balances (
    id           bigint generated by default as identity primary key,
    team_id      bigint      not null references teams (id),
    account_key  varchar(40) not null,
    asset        varchar(40) not null,
    amount       bigint      not null,
    constraint uq_balances unique (team_id, account_key, asset)
);

create table ledger_entries (
    id             bigint generated by default as identity primary key,
    team_id        bigint       not null references teams (id),
    txn            varchar(36)  not null,
    account_key    varchar(40)  not null,
    asset          varchar(40)  not null,
    delta          bigint       not null,
    balance_after  bigint       not null,
    reason         varchar(24)  not null,
    mission_id     bigint,
    actor_id       bigint       references users (id),
    memo           varchar(140),
    created_at     timestamp with time zone not null
);
create index ix_ledger_team on ledger_entries (team_id, id);
create index ix_ledger_txn on ledger_entries (txn);

create table team_events (
    id          bigint generated by default as identity primary key,
    team_id     bigint       not null references teams (id),
    actor_id    bigint       references users (id),
    type        varchar(32)  not null,
    summary     varchar(200) not null,
    created_at  timestamp with time zone not null
);
create index ix_events_team on team_events (team_id, id);
