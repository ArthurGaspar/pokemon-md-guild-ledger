create table certificates (
    id             bigint generated by default as identity primary key,
    run_id         varchar(36)              not null,
    expedition_id  bigint                   not null,
    party_id       bigint                   not null,
    adventurer_id  varchar(64)              not null,
    role           varchar(10)              not null,
    floors_cleared int                      not null,
    poke_share     int                      not null,
    issued_at      timestamp with time zone not null,
    -- the second line of defence after the inbox: one certificate per member per run, whatever happens
    unique (run_id, adventurer_id)
);

create index certificates_by_adventurer on certificates (adventurer_id, id);

create table notifications (
    id            bigint generated by default as identity primary key,
    adventurer_id varchar(64)              not null,
    kind          varchar(40)              not null,
    message       varchar(300)             not null,
    expedition_id bigint                   not null,
    created_at    timestamp with time zone not null
);

create index notifications_by_adventurer on notifications (adventurer_id, id);
