-- This service's copy of each expedition: the composition, and the open-slot counter it serializes on.
create table expeditions (
    id               bigint primary key,
    code             varchar(40)              not null,
    opens_at         timestamp with time zone not null,
    parties          int                      not null,
    tanks            int                      not null,
    healers          int                      not null,
    damage           int                      not null,
    open_slots       int                      not null check (open_slots >= 0),
    capacity_version bigint                   not null
);

create table parties (
    id            bigint generated by default as identity primary key,
    expedition_id bigint                   not null references expeditions (id),
    number        int                      not null,
    status        varchar(16)              not null,
    ready_by      timestamp with time zone,
    locked_at     timestamp with time zone,
    unique (expedition_id, number)
);

create index parties_by_status on parties (expedition_id, status);
create index parties_ready_check on parties (status, ready_by);

create table reservations (
    id            bigint generated by default as identity primary key,
    expedition_id bigint                   not null references expeditions (id),
    party_id      bigint                   not null references parties (id),
    adventurer_id varchar(64)              not null,
    role          varchar(10)              not null,
    status        varchar(16)              not null,
    held_until    timestamp with time zone,
    created_at    timestamp with time zone not null,
    closed_at     timestamp with time zone
);

create index reservations_by_party on reservations (party_id, status);
create index reservations_by_adventurer on reservations (adventurer_id, expedition_id);
create index reservations_holds on reservations (status, held_until);
